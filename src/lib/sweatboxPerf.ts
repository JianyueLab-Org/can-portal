/**
 * Aircraft performance blocks for generated SweatBox scenarios.
 *
 * `PERFAC:<type>` opens a block and each `PERFLINE:` under it is one altitude
 * band:
 *
 *   PERFLINE:<FL/10>:<climb IAS>:<cruise IAS>:<descent IAS>
 *            :<climb Mach>:<cruise Mach>:<descent Mach>
 *            :<climb rate>:<descent rate>
 *
 * IAS and Mach are exclusive per band — the low bands carry speeds with
 * `000` Mach, the high bands the reverse, and the altitude at which a type
 * crosses over is part of what makes it fly like itself.
 *
 * **These are transcribed, not derived.** Every table below is lifted verbatim
 * from the hand-written scenarios in `SweatBox/` (the ZGGG tower set carries
 * all fourteen), which are contributed training material with their authors'
 * handles on them. They are somebody's tuning against EuroScope's own model,
 * accumulated over years of running these sessions; a table computed from a
 * performance manual would be more defensible on paper and would fly worse.
 * So: correct a value only against a scenario that has been flown, and if a
 * type is missing here, take its block from a working scenario rather than
 * interpolating a neighbour.
 *
 * A generated scenario emits only the blocks its aircraft actually use.
 * EuroScope falls back to a generic model for a type with no block, which is
 * survivable for one odd airframe and ruinous for a whole session.
 */

